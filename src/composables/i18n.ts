export type Dictionary = typeof en;
type DeepPartial<T> = { [K in keyof T]?: T[K] extends object ? DeepPartial<T[K]> : T[K] };

const dictionaries: Record<LanguageCode, DeepPartial<Dictionary>> = { en, ru, hi, zh, ar };

function lookup(dict: DeepPartial<Dictionary>, path: string): string | undefined {
  return path
    .split('.')
    .reduce<unknown>((node, key) => (node && typeof node === 'object' ? (node as Record<string, unknown>)[key] : undefined), dict) as
    | string
    | undefined;
}

/** Shared translation helper — reads the language reactively. */
export function useI18n() {
  const { settings } = useSettings();

  const language = computed(() => settings.language);
  const direction = computed(() => LANGUAGES.find((l) => l.code === language.value)?.dir ?? 'ltr');

  function t(path: string): string {
    const value = lookup(dictionaries[language.value], path);
    if (value === undefined) {
      if (import.meta.env.DEV) console.warn(`[i18n] missing key: ${path}`);
      return lookup(dictionaries.en, path) ?? path;
    }
    return value;
  }

  return { t, language, direction };
}

/** `12:34` / `1:02:03` style clock used by the queue timers. */
export function formatClock(totalSeconds: number): string {
  const seconds = Math.max(0, Math.floor(totalSeconds));
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = seconds % 60;
  const pad = (n: number) => String(n).padStart(2, '0');
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${pad(m)}:${pad(s)}`;
}
